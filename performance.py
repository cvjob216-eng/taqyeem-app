GENERIC = ["وضعيات علاجية متدرجة تنطلق من المحسوس إلى المجرد مع متابعة فردية"]


def _opts(subject, text):
    found = [(lab, rems) for lab, keys, rems in TOPICS.get(subject, []) if any(k in text for k in keys)]
    if not found:
        return GENERIC[:], GENERIC[:1]
    multi = len(found) > 1
    allr, first = [], []
    for lab, rems in found:
        fm = [f"{lab}: {r}" if multi else r for r in rems]
        allr += fm
        first.append(fm[0])
    return allr, first


def suggest(subject, text):
    """كل الحلول المقترحة لمكوّن من الأداء المنتظر"""
    return _opts(subject, text)[0]


def default_rem(subject, text):
    """الحلول المفعّلة افتراضياً (أول حل لكل موضوع مطابق)"""
    return _opts(subject, text)[1]
